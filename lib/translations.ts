const dictionaries: Record<Lang, Record<string, string>> = { en, th };

export const hasKey = (key: string) => key in en;

/** Looks up `key`, falls back to English, then to the key itself. Replaces {placeholders}. */
export function translate(lang: Lang, key: string, vars?: Vars): string {
    const raw = dictionaries[lang][key] ?? en[key as TKey] ?? key;
    if (!vars) return raw;
    return raw.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}